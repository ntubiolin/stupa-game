// Run with Node from a checkout with Playwright and Chrome installed.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { createServer } from 'vite';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const server = await createServer({root, configFile: false, server: {host: '127.0.0.1', port: 0}});
await server.listen();
const browser = await chromium.launch({channel: 'chrome', headless: true});
try {
  const page = await browser.newPage();
  await page.route('**/atlas-export', route => route.fulfill({contentType: 'text/html',
    body: '<canvas width="1600" height="900"></canvas>'}));
  await page.goto(server.resolvedUrls.local[0] + 'atlas-export');
  const {jpeg, nodes, edges} = await page.evaluate(async () => {
    const {MuralScrollCanvas} = await import('/src/ui/mural/scroll.js');
    const {WORLD_ROUTE_NODES} = await import('/src/ui/worldmap.js');
    const {i18n} = await import('/src/i18n.js');
    const route = WORLD_ROUTE_NODES.filter(n => !n.japanOnly && !n.debugOnly);
    const canvas = document.querySelector('canvas');
    const scroll = new MuralScrollCanvas(canvas, {chapterId: 'prologue'});
    scroll.mural = {...scroll.mural, paths: [], episodes: []};
    scroll.draw();
    const g = canvas.getContext('2d');
    // Set each original painted landmark against its own route pin.
    const art = {
      stupa: ['boudha_stupa', 236], grove: ['villagers', 114], wild: ['white_yak', 114],
      pharping: ['cave', 136], mangyul: ['tibetan_envoy', 130],
      yarlung: ['yumbulagang', 170], samye: ['samye_mandala', 162],
      chimphu: ['yeshe_tsogyal', 96], terma: ['kilaya', 146],
    };
    const nodes = [];
    const edges = [];
    const dict = i18n.getStrings();
    for (const [index, n] of route.entries()) {
      const [id, h] = art[n.id];
      const img = new Image();
      img.src = '/murals/' + id + '.webp';
      await img.decode();
      const w = h * img.naturalWidth / img.naturalHeight;
      g.drawImage(img, n.nx*1600-w/2, n.ny*900-h+11, w, h);
      nodes.push([n.nx,n.ny,dict.en[n.nameKey],dict.zh[n.nameKey],dict.en[n.descKey],dict.zh[n.descKey]]);
      for (const key of n.connectsTo) {
        const other = route.findIndex(x => x.id === key);
        if (other >= 0 && !edges.some(([a,b]) => a===other && b===index)) edges.push([index, other]);
      }
    }
    return {jpeg: canvas.toDataURL('image/jpeg', .9).split(',')[1], nodes, edges};
  });
  const project = new URL('../', import.meta.url);
  await writeFile(new URL('Assets/Journal/PilgrimageAtlas.jpg', project), Buffer.from(jpeg,'base64'));
  const quoted = s => 'TEXT(' + JSON.stringify(s) + ')';
  const rows = nodes.map(([x,y,...strings]) => '    {'+[x+'f',y+'f',...strings.map(quoted)].join(', ' )+'},');
  const source = '// Generated by Tools/export_atlas.mjs from the web world map.\nconst FAtlasNode AtlasNodes[] = {\n'+rows.join('\n')+'\n};\nconst FIntPoint AtlasEdges[] = {'+edges.map(([a,b])=>'{'+a+','+b+'}').join(', ')+'};\n';
  await writeFile(new URL('Source/TibetPilgrimage/TibetAtlasNodes.inl',project),source);
} finally {
  await browser.close();
  await server.close();
}
